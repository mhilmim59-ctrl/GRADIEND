window.openKeajaiban = function () {
  const data = window.GRADIEND_KEAJAIBAN || [];
  const esc = window.escapeHtml;
  let m = document.getElementById("keajaiban-modal");
  if (!m) {
    m = document.createElement("div");
    m.id = "keajaiban-modal";
    m.className = "modal";
    m.setAttribute("role", "dialog");
    m.setAttribute("aria-modal", "true");
    m.setAttribute("aria-labelledby", "kj-title");
    m.innerHTML = `<div class="modal-card kj-card">
      <button type="button" class="modal-close" aria-label="Tutup">&times;</button>
      <div class="eyebrow">Fitur tersembunyi</div>
      <h2 class="modal-title" id="kj-title">Keajaiban Al-Qur'an dan Sains</h2>
      <p class="modal-sub">Ayat-ayat yang sering dikaitkan dengan temuan sains. Ketuk judul untuk membuka.</p>
      <div class="kj-list">${data.map((x, i) => `<details class="kj-item"${i === 0 ? " open" : ""}>
        <summary><span class="kj-ico"><i class="fa-solid ${esc(x.ikon)}"></i></span><span>${esc(x.judul)}</span></summary>
        <div class="kj-body">
          <div class="kj-ar" lang="ar" dir="rtl">${esc(x.ar)}</div>
          <p class="kj-id">${esc(x.terjemah)}</p>
          <small class="kj-ref">${esc(x.ref)}</small>
          <div class="kj-sains"><b><i class="fa-solid fa-flask"></i> Kaitan dengan sains</b><p>${esc(x.sains)}</p></div>
          <div class="kj-note"><i class="fa-solid fa-circle-info"></i> ${esc(x.catatan)}</div>
        </div></details>`).join("")}</div>
      <div class="notice" style="margin-top:14px">Al-Qur'an adalah kitab petunjuk, bukan buku sains. Kaitan di atas adalah tafsir ilmi yang bisa berbeda antar ahli, dan pemahaman sains pun terus berkembang. Untuk makna ayat yang baku, rujuklah tafsir para ulama.</div>
    </div>`;
    document.body.appendChild(m);
    const close = () => { m.classList.remove("open"); document.body.style.overflow = ""; };
    m.addEventListener("click", e => { if (e.target === m || e.target.closest(".modal-close")) close(); });
    document.addEventListener("keydown", e => { if (e.key === "Escape" && m.classList.contains("open")) close(); });
  }
  requestAnimationFrame(() => m.classList.add("open"));
  document.body.style.overflow = "hidden";
};
